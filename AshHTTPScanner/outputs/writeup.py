def show_writeup(target_address, http_response, http_status_code, protocol, header_list, response_time):
    file = open('AshHTTPScanner/reports/report.txt', "w")
    file.write("="*120+"\n")
    file.write("ASH HTTP SCANNER\n")
    file.write("="*120+"\n")
    file.write("\n")
    file.write("Target".ljust(19)+":"+ target_address + "\n")
    file.write("Protocol".ljust(19)+":"+ protocol.get("protocol") + "\n")
    file.write("\n")
    file.write("-"*120+"\n")
    file.write("HTTP RESPONSE\n")
    file.write("-"*120+"\n")
    file.write("\n")
    file.write("Status Code".ljust(19)+":"+ str(http_status_code.get("Status Code", "Unknown")) + "\n")
    file.write("Status Message".ljust(19)+":"+"OK\n")
    file.write("\n")
    file.write("-"*120+"\n")
    file.write("RESPONSE HEADERS\n")
    file.write("-"*120+"\n")
    file.write("Response Time".ljust(19)+":"+ str(response_time) + "\n") 
    for loop in header_list: 
     final_http = http_response.get(loop)
     file.write(loop.ljust(19)+":"+ str(final_http) + "\n")
    file.write("\n")         
    file.close()